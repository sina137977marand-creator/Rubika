DICE_RE = re.compile(r"^تاس(?:\s+(\d+))?$")


async def handle_dice_text(bot, message) -> bool:
    text = (message.text or "").strip()
    m = DICE_RE.match(text)
    if not m:
        return False
    await _roll_dice(message, m.group(1))
    return True


async def _roll_dice(message, count_str):
    if not count_str:
        val = random.randint(1, 6)
        face = DICE_FACES[val]
        await areply(message, f"🎲 تاس انداختی...\n\n{face}  عدد {val} اومد!")
        return
    try:
        count = int(count_str)
    except ValueError:
        await areply(message, "عدد نامعتبره. مثال: تاس 10")
        return
    count = max(1, min(count, config.MAX_DICE_COUNT))
    rolls = [random.randint(1, 6) for _ in range(count)]
    total = sum(rolls)
    faces_line = " ".join(DICE_FACES[r] for r in rolls)
    nums_line = " + ".join(str(r) for r in rolls)
    await areply(
        message,
        f"{title('نتیجه تاس‌ها', '🎲')}\n"
        f"{faces_line}\n\n"
        f"{nums_line} = 🏆 {total}"
    )


