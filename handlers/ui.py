# -*- coding: utf-8 -*-
"""
کمک‌کننده‌های طراحی/دیزاین برای پیام‌های متنی.

نکته‌ی مهم (نتیجه‌ی تست واقعی و مستندات رسمی روبیکا): کلیک روی دکمه‌ی شیشه‌ای
(Inline Keypad) فقط از طریق وب‌هوک قابل دریافته، نه از طریق polling ساده‌ای که
این ربات (و اکثر ربات‌های تست‌شده روی گوشی/بدون سرور عمومی) استفاده می‌کنه. برای
همین این پروژه دیگه از هیچ نوع دکمه (نه شیشه‌ای، نه Chat Keypad) استفاده نمی‌کنه؛
همه‌چیز کاملاً متنی و از طریق polling کار می‌کنه که همیشه قابل‌اعتماده.
اگه بعداً روی سروری با دامنه و HTTPS مستقر شدید و وب‌هوک راه انداختید، اونجا
می‌شه دوباره دکمه اضافه کرد.
"""

DIVIDER = "┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄"


def title(text: str, emoji: str = "✨") -> str:
    """یه سربرگ شیک برای پیام‌ها."""
    return f"{emoji} {text} {emoji}\n{DIVIDER}"


def kv(label: str, value) -> str:
    """یه خط «برچسب: مقدار» با فرمت یکدست."""
    return f"▫️ {label}: {value}"


def section(text: str) -> str:
    return f"\n{DIVIDER}\n{text}"
