async def quiz_command(bot, message):
    group_id = message.chat_id
    q = random.choice(QUESTIONS)
    options_text = "\n".join(f"{i+1}. {opt}" for i, opt in enumerate(q["options"]))
    db.set_active_quiz(group_id, q["q"], str(q["correct"]))
    await areply(
        message,
        f"{title('کوییز', '❓')}\n"
        f"{q['q']}\n\n{options_text}\n\n"
        "💡 برای پاسخ، فقط عدد گزینه‌ی درست رو بفرست."
    )


async def try_answer_quiz(bot, message) -> bool:
    group_id = message.chat_id
    text = (message.text or "").strip()
    if not text.isdigit():
        return False
    active = db.get_active_quiz(group_id)
    if not active:
        return False
    if text == active["correct_answer"]:
        name = await safe_name(bot, message.sender_id, group_id=message.chat_id)
        db.add_quiz_score(group_id, message.sender_id, name or "کاربر", points=1)
        db.clear_active_quiz(group_id)
        await areply(message, f"✅ آفرین {name}! جواب درست بود. یک امتیاز گرفتی. 🏅")
        return True
    return False


async def quiz_score_command(bot, message):
    top = db.top_quiz_scores(message.chat_id, limit=10)
    if not top:
        await areply(message, "هنوز کسی امتیازی نگرفته. با «کوییز» شروع کن!")
        return
    lines = [title("جدول امتیازات کوییز", "🏆")]
    medals = ["🥇", "🥈", "🥉"]
    for i, row in enumerate(top, start=1):
        medal = medals[i - 1] if i <= 3 else f"{i}."
        lines.append(f"{medal} {row['full_name']} — {row['score']} امتیاز")
    await areply(message, "\n".join(lines))
